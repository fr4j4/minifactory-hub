import { unzipSync, strFromU8 } from 'fflate';
import { XMLParser } from 'fast-xml-parser';

/** Metadatos de un G-code o 3MF laminado (modo semiautomático) */
export interface SliceMeta {
  slicer: string | null;          // OrcaSlicer 2.4.2, PrusaSlicer 2.7, Cura 5.x, BambuStudio…
  timeS: number | null;           // tiempo total estimado en segundos
  filaments: Array<{ g: number | null; mm: number | null; cm3: number | null; type?: string; color?: string }>;
  totalG: number | null;
  layers: number | null;
  layerHeight: number | null;
  plates?: number;
  maxZ: number | null;
  machine: string | null;
  filamentChanges?: number;
  notes: string[];
}

const num = (s?: string) => (s == null || s === '' ? null : Number.isFinite(+s) ? +s : null);
const nums = (s: string) => s.split(/[,;]/).map((x) => num(x.trim())).filter((x): x is number => x !== null);

export function parseDuration(s: string): number | null {
  // "1d 2h 3m 4s", "32m 23s", "1h 2m"
  let total = 0, found = false;
  for (const m of s.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)) {
    found = true; const v = +m[1];
    total += m[2] === 'd' ? v * 86400 : m[2] === 'h' ? v * 3600 : m[2] === 'm' ? v * 60 : v;
  }
  return found ? Math.round(total) : null;
}

/** Lee encabezado y pie de un G-code (donde los laminadores escriben sus resúmenes). */
export function parseGcodeMeta(text: string, opts: { defaultDensity?: number; defaultDiameter?: number } = {}): SliceMeta {
  const head = text.slice(0, 200_000);
  const tail = text.length > 400_000 ? text.slice(-200_000) : '';
  const hay = head + '\n' + tail;
  const meta: SliceMeta = { slicer: null, timeS: null, filaments: [], totalG: null, layers: null, layerHeight: null, maxZ: null, machine: null, notes: [] };
  const g = (re: RegExp) => hay.match(re)?.[1]?.trim();

  meta.slicer = g(/^;\s*generated by\s+(.+)$/im)?.replace(/\s+on\s+\d{4}-.*$/, '') ?? (g(/^;Generated with\s+(.+)$/im) ?? null);
  if (!meta.slicer && /^;FLAVOR:/m.test(hay)) meta.slicer = 'Cura';

  // tiempo
  const tTotal = g(/^;\s*total estimated time:\s*(.+?)(?:;|$)/im) ?? g(/^;\s*model printing time:.*?total estimated time:\s*(.+)$/im);
  const tModel = g(/^;\s*model printing time:\s*(.+?)(?:;|$)/im);
  const tPrusa = g(/^;\s*estimated printing time \(normal mode\)\s*=\s*(.+)$/im);
  const tCura = g(/^;TIME:(\d+)/m);
  if (tTotal) meta.timeS = parseDuration(tTotal);
  else if (tPrusa) meta.timeS = parseDuration(tPrusa);
  else if (tCura) meta.timeS = +tCura;
  else if (tModel) { meta.timeS = parseDuration(tModel); meta.notes.push('gcodeNote.modelTimeOnly'); }

  // filamento (Orca/Bambu/Prusa)
  const mm = g(/^;\s*filament used \[mm\]\s*=\s*(.+)$/im);
  const cm3 = g(/^;\s*filament used \[cm3\]\s*=\s*(.+)$/im);
  const grams = g(/^;\s*filament used \[g\]\s*=\s*(.+)$/im);
  const dens = g(/^;\s*filament_density\s*[:=]\s*(.+)$/im);
  const diam = g(/^;\s*filament_diameter\s*[:=]\s*(.+)$/im);
  const colours = g(/^;\s*filament_colour\s*=\s*(.+)$/im);
  const ftype = g(/^;\s*filament_type\s*=\s*(.+)$/im);
  if (mm || grams || cm3) {
    const A = mm ? nums(mm) : [], B = cm3 ? nums(cm3) : [], C = grams ? nums(grams) : [];
    const n = Math.max(A.length, B.length, C.length);
    const dArr = dens ? nums(dens) : [], dmArr = diam ? nums(diam) : [];
    for (let i = 0; i < n; i++) {
      let gr = C[i] ?? null;
      const d = dArr[i] ?? dArr[0] ?? opts.defaultDensity ?? 1.24;
      const dm = dmArr[i] ?? dmArr[0] ?? opts.defaultDiameter ?? 1.75;
      if (gr == null && A[i] != null) gr = ((Math.PI * (dm / 2) ** 2 * A[i]) / 1000) * d; // mm³→cm³ × densidad
      if (gr == null && B[i] != null) gr = B[i] * d;
      meta.filaments.push({ g: gr, mm: A[i] ?? null, cm3: B[i] ?? null, color: colours?.split(';')[i], type: ftype?.split(';')[i]?.replace(/"/g, '') });
    }
  } else {
    // Cura: ";Filament used: 1.234m" (puede haber varios extrusores separados por coma)
    const fu = g(/^;Filament used:\s*(.+)$/im);
    if (fu) {
      const d = opts.defaultDensity ?? 1.24, dm = opts.defaultDiameter ?? 1.75;
      for (const part of fu.split(',')) {
        const m = part.trim().match(/([\d.]+)\s*m/);
        if (m && +m[1] > 0) { const mmv = +m[1] * 1000; meta.filaments.push({ mm: mmv, cm3: (Math.PI * (dm / 2) ** 2 * mmv) / 1000, g: ((Math.PI * (dm / 2) ** 2 * mmv) / 1000) * d }); }
      }
      meta.notes.push('gcodeNote.curaMeters');
    }
  }
  const tf = g(/^;\s*total filament used \[g\]\s*=\s*([\d.]+)/im) ?? g(/^;\s*total filament weight \[g\]\s*:\s*([\d.]+)/im);
  meta.totalG = num(tf) ?? (meta.filaments.length ? meta.filaments.reduce((a, f) => a + (f.g ?? 0), 0) : null);

  meta.layers = num(g(/^;\s*total layer number:\s*(\d+)/im)) ?? num(g(/^;LAYER_COUNT:(\d+)/m)) ?? num(g(/^;\s*total layers count\s*=\s*(\d+)/im));
  meta.layerHeight = num(g(/^;\s*layer_height\s*=\s*([\d.]+)/im)) ?? num(g(/^;Layer height:\s*([\d.]+)/im));
  meta.maxZ = num(g(/^;\s*max_z_height:\s*([\d.]+)/im)) ?? num(g(/^;MAXZ:([\d.]+)/m));
  meta.machine = g(/^;\s*printer_settings_id\s*=\s*(.+)$/im) ?? g(/^;\s*printer_model\s*=\s*(.+)$/im) ?? null;
  const changes = (hay.match(/^M600|^T[1-9]\s*$|^;\s*CHANGE_LAYER|^;\s*filament change/gim) ?? []).length;
  if (changes > 0 && meta.filaments.length > 1) meta.filamentChanges = changes;
  if (meta.timeS == null && !meta.filaments.length) meta.notes.push('gcodeNote.noSummary');
  return meta;
}

/** 3MF laminado (Bambu Studio / OrcaSlicer): slice_info.config + G-code embebido por placa */
export function parse3mfSliceMeta(buf: Uint8Array): SliceMeta | null {
  let files: Record<string, Uint8Array>;
  try { files = unzipSync(buf, { filter: (f) => /slice_info\.config$|plate_\d+\.gcode$|project_settings\.config$/i.test(f.name) }); } catch { return null; }
  const info = Object.keys(files).find((n) => /slice_info\.config$/i.test(n));
  const gcodes = Object.keys(files).filter((n) => /plate_\d+\.gcode$/i.test(n)).sort();
  if (!info && !gcodes.length) return null;
  const meta: SliceMeta = { slicer: null, timeS: null, filaments: [], totalG: null, layers: null, layerHeight: null, maxZ: null, machine: null, notes: [], plates: 0 };
  if (info) {
    const doc = new XMLParser({ ignoreAttributes: false, attributeNamePrefix: '@_', isArray: (n) => ['plate', 'metadata', 'filament'].includes(n) }).parse(strFromU8(files[info]));
    const header = doc?.config?.header?.header_item;
    const hv = Array.isArray(header) ? header : header ? [header] : [];
    const hs = hv.find((h: any) => h['@_key'] === 'X-BBL-Client-Version' || h['@_key'] === 'BambuStudio');
    const plates = doc?.config?.plate ?? [];
    meta.plates = plates.length;
    let tt = 0; const fil: Record<string, { g: number; mm: number; color?: string; type?: string }> = {};
    for (const p of plates) {
      for (const m of p.metadata ?? []) {
        if (m['@_key'] === 'prediction') tt += +m['@_value'];
        if (m['@_key'] === 'printer_model_id') meta.machine = meta.machine ?? m['@_value'];
      }
      for (const f of p.filament ?? []) {
        const k = f['@_id']; const e = (fil[k] ??= { g: 0, mm: 0, color: f['@_color'], type: f['@_type'] });
        e.g += +(f['@_used_g'] ?? 0); e.mm += +(f['@_used_m'] ?? 0) * 1000;
      }
    }
    meta.timeS = tt || null;
    meta.filaments = Object.values(fil).map((f) => ({ g: f.g, mm: f.mm, cm3: null, color: f.color, type: f.type }));
    meta.totalG = meta.filaments.reduce((a, f) => a + (f.g ?? 0), 0) || null;
    meta.slicer = hs?.['@_value'] ? `Bambu/Orca ${hs['@_value']}` : 'Bambu Studio / OrcaSlicer';
  }
  if (gcodes.length) {
    const g0 = parseGcodeMeta(strFromU8(files[gcodes[0]]));
    meta.layers = g0.layers; meta.layerHeight = g0.layerHeight; meta.maxZ = g0.maxZ; meta.slicer = g0.slicer ?? meta.slicer; meta.machine = g0.machine ?? meta.machine;
    if (meta.timeS == null) meta.timeS = g0.timeS;
    if (!meta.filaments.length) { meta.filaments = g0.filaments; meta.totalG = g0.totalG; }
    meta.plates = Math.max(meta.plates ?? 0, gcodes.length);
  }
  if (meta.timeS == null && !meta.filaments.length) meta.notes.push('gcodeNote.unsliced3mf');
  return meta;
}

export function hasSlicedData(m: SliceMeta | null): m is SliceMeta {
  return !!m && (m.timeS != null || m.filaments.length > 0);
}

/* ───────────────────────── Vista previa por capas ───────────────────────── */
export const GCODE_TYPES = ['perimetro', 'relleno', 'superficie', 'soporte', 'otro'] as const;
export type GType = (typeof GCODE_TYPES)[number];

function classify(label: string): GType {
  const l = label.toLowerCase();
  if (/wall|perimeter|overhang|external|outer|inner/.test(l)) return 'perimetro';
  if (/top|bottom|skin|bridge|solid/.test(l)) return 'superficie';
  if (/infill|fill/.test(l)) return 'relleno';
  if (/support/.test(l)) return 'soporte';
  return 'otro';
}

export interface PreviewStats {
  /** tiempo (s) y largo extruido (mm) por tipo, en el orden de GCODE_TYPES */
  byType: Array<{ timeS: number; mm: number }>;
  /** tiempo estimado de extrusión de cada capa (s) */
  layerTimeS: number[];
  speed: [number, number]; width: [number, number];
}
export interface GcodePreview {
  bbox: { min: [number, number, number]; max: [number, number, number] };
  layers: Array<{ z: number; t: Array<[number, number, number]> /* tipo, offset, cantidad (en segmentos) */ }>;
  segments: Float32Array; // x1,y1,x2,y2 por segmento
  /** velocidad (mm/s) y ancho de línea (mm) por segmento, en el mismo orden que `segments` */
  speeds: Float32Array; widths: Float32Array;
  stats: PreviewStats;
  total: number;
  sampled: boolean;
}

export function buildGcodePreview(text: string, maxSegments = 1_200_000): GcodePreview {
  let x = 0, y = 0, z = 0, e = 0, relE = false, absPos = true, curType: GType = 'otro';
  let layerIdx = -1; let curLayerZ = -Infinity; let feed = 0; let curWidth = 0.42;
  const perLayer: Array<{ z: number; segs: Record<number, number[]>; spd: Record<number, number[]>; wid: Record<number, number[]> }> = [];
  const typeAcc = GCODE_TYPES.map(() => ({ timeS: 0, mm: 0 }));
  let total = 0;
  const min: [number, number, number] = [Infinity, Infinity, Infinity], max: [number, number, number] = [-Infinity, -Infinity, -Infinity];
  const lines = text.split('\n');
  const stride = lines.length > maxSegments * 1.2 ? Math.ceil((lines.length / maxSegments)) : 1;
  let counter = 0;
  for (let li = 0; li < lines.length; li++) {
    const line = lines[li];
    const c = line.charCodeAt(0);
    if (c === 59 /* ; */) {
      if (line.startsWith(';TYPE:') || line.startsWith('; FEATURE:')) curType = classify(line.replace(/^;\s*(TYPE|FEATURE):/, ''));
      else if (line.startsWith('; LINE_WIDTH:')) { const w = parseFloat(line.slice(13)); if (Number.isFinite(w)) curWidth = w; }
      continue;
    }
    if (c !== 71 /* G */ && c !== 77 /* M */) continue;
    if (line.startsWith('M82')) { relE = false; continue; }
    if (line.startsWith('M83')) { relE = true; continue; }
    if (line.startsWith('G90')) { absPos = true; continue; }
    if (line.startsWith('G91')) { absPos = false; continue; }
    if (line.startsWith('G92')) { const m = line.match(/E(-?[\d.]+)/); if (m) e = +m[1]; continue; }
    if (!(line.startsWith('G1 ') || line.startsWith('G0 ') || line.startsWith('G2 ') || line.startsWith('G3 '))) continue;
    let nx = x, ny = y, nz = z, ne = e, hasE = false;
    const semi = line.indexOf(';');
    const body = semi >= 0 ? line.slice(0, semi) : line;
    for (const tok of body.split(' ')) {
      const ch = tok[0]; if (!ch || tok.length < 2) continue;
      const v = parseFloat(tok.slice(1)); if (!Number.isFinite(v)) continue;
      if (ch === 'X') nx = absPos ? v : x + v; else if (ch === 'Y') ny = absPos ? v : y + v; else if (ch === 'Z') nz = absPos ? v : z + v;
      else if (ch === 'E') { hasE = true; ne = relE ? e + v : v; }
      else if (ch === 'F') feed = v / 60;
    }
    const extruding = hasE && ne > e + 1e-6 && (nx !== x || ny !== y);
    if (extruding) {
      if (nz !== curLayerZ || layerIdx < 0) { curLayerZ = nz; layerIdx = perLayer.length; perLayer.push({ z: nz, segs: {}, spd: {}, wid: {} }); }
      const len = Math.hypot(nx - x, ny - y); const spd = feed > 0 ? feed : 60; const ti0 = GCODE_TYPES.indexOf(curType);
      typeAcc[ti0].mm += len; typeAcc[ti0].timeS += len / spd; (perLayer[layerIdx] as any).t = ((perLayer[layerIdx] as any).t ?? 0) + len / spd;
      const keep = stride === 1 || curType !== 'relleno' || counter++ % stride === 0;
      if (keep) {
        const ti = GCODE_TYPES.indexOf(curType);
        (perLayer[layerIdx].segs[ti] ??= []).push(x, y, nx, ny); (perLayer[layerIdx].spd[ti] ??= []).push(spd); (perLayer[layerIdx].wid[ti] ??= []).push(curWidth); total++;
      }
      if (x < min[0]) min[0] = x; if (nx < min[0]) min[0] = nx; if (x > max[0]) max[0] = x; if (nx > max[0]) max[0] = nx;
      if (y < min[1]) min[1] = y; if (ny < min[1]) min[1] = ny; if (y > max[1]) max[1] = y; if (ny > max[1]) max[1] = ny;
      if (nz < min[2]) min[2] = nz; if (nz > max[2]) max[2] = nz;
    }
    x = nx; y = ny; z = nz; e = ne;
  }
  const flat: number[] = []; const fs: number[] = []; const fw: number[] = [];
  const layers = perLayer.map((l) => {
    const tt: Array<[number, number, number]> = [];
    for (const ti of Object.keys(l.segs).map(Number).sort()) { const arr = l.segs[ti]; tt.push([ti, flat.length / 4, arr.length / 4]); for (let i = 0; i < arr.length; i++) flat.push(arr[i]); fs.push(...l.spd[ti]); fw.push(...l.wid[ti]); }
    return { z: l.z, t: tt };
  });
  if (!isFinite(min[0])) { min.fill(0); max.fill(0); }
  const rng = (a: number[]): [number, number] => (a.length ? [a.reduce((m, v) => Math.min(m, v), Infinity), a.reduce((m, v) => Math.max(m, v), -Infinity)] : [0, 0]);
  const stats: PreviewStats = { byType: typeAcc.map((x) => ({ timeS: +x.timeS.toFixed(1), mm: +x.mm.toFixed(0) })), layerTimeS: perLayer.map((l) => +(((l as any).t ?? 0) as number).toFixed(1)), speed: rng(fs), width: rng(fw) };
  return { bbox: { min, max }, layers, segments: Float32Array.from(flat), speeds: Float32Array.from(fs), widths: Float32Array.from(fw), stats, total, sampled: stride > 1 };
}

export function gcodePreviewToBin(p: GcodePreview): Buffer {
  // MFG2: posiciones, luego velocidad y ancho por segmento (el visor también lee MFG1, sin atributos)
  const head = Buffer.from(JSON.stringify({ bbox: p.bbox, layers: p.layers, types: GCODE_TYPES, total: p.total, sampled: p.sampled, stats: p.stats, segCount: p.segments.length / 4 }));
  const len = Buffer.alloc(8); len.write('MFG2', 0, 'ascii'); len.writeUInt32LE(head.length, 4);
  const b = (a: Float32Array) => Buffer.from(a.buffer, a.byteOffset, a.byteLength);
  return Buffer.concat([len, head, b(p.segments), b(p.speeds), b(p.widths)]);
}
